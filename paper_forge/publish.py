"""Save approved drafts onto a fresh LOCAL branch of fluentedge-coding-problems.

Never pushes. Never opens a PR. Commits only when asked (commit=True).
The branch is cut from origin/main, so unrelated work in the current checkout is never mixed in.
"""
from __future__ import annotations

import json
import re
import shutil
import time
import subprocess
import sys
from pathlib import Path

from . import review
from .config import Config
from .layout import company_dir


class PublishError(RuntimeError):
    pass


def git(cwd: Path, *args: str, check: bool = True) -> str:
    r = subprocess.run(["git", "-C", str(cwd), *args], capture_output=True, text=True, encoding="utf-8", errors="replace")
    if check and r.returncode != 0:
        raise PublishError(f"git {' '.join(args)} failed:\n{(r.stderr or r.stdout).strip()}")
    return r.stdout.strip()


def add_to_pool(text: str, round_key: str, paper_key: str) -> str:
    """Add paper_key to the paperPool of one round by editing the text, so the file's formatting is kept."""
    at = text.find(f'"roundKey": "{round_key}"')
    if at == -1:
        raise PublishError(f"Round {round_key!r} not found in company.json")
    m = re.compile(r'(^[ \t]*)"paperPool"\s*:\s*\[(.*?)\]', re.S | re.M).search(text, at)
    if not m:
        raise PublishError(f"No paperPool found for round {round_key!r}")
    items = re.findall(r'"([^"]+)"', m.group(2))
    if paper_key in items:
        raise PublishError(f"{paper_key} is already in the paperPool")
    items.append(paper_key)
    indent = m.group(1)
    body = ",\n".join(f'{indent}  "{i}"' for i in items)
    return text[:m.start()] + f'{indent}"paperPool": [\n{body}\n{indent}]' + text[m.end():]


def branch_name(slug: str, keys: list[str], tree: str) -> str:
    nums = sorted(int(re.search(r"-(\d{3})$", k).group(1)) for k in keys)
    span = f"{nums[0]:03d}" if len(nums) == 1 else f"{nums[0]:03d}-{nums[-1]:03d}"
    mid = "university-papers" if tree == "university" else "papers"
    return f"feat/{slug}-{mid}-{span}"


def developer_task_md(key: str, pending: list[dict]) -> str:
    out = [f"# Developer task: image question support ({key})", "",
           "Paper Forge wrote these questions as content but kept them out of the paper, because the paper schema,",
           "validator, backend and student screen have no image field yet.", "",
           "## Needed", "1. Image field in the paper schema and `validate_placement_papers.py`",
           "2. bet-retail-service reads and serves it", "3. bet-apps student exam screen shows it",
           "4. Designer draws each brief below; tester signs off before the section goes live", ""]
    for sec in pending:
        out += [f"## {sec['section']} ({len(sec['questions'])} questions)", ""]
        for i, q in enumerate(sec["questions"], 1):
            out += [f"### Q{i} [{q.get('complexity', '')}]", q.get("question", ""),
                    f"- Options: " + " | ".join(f"{k}. {v}" for k, v in (q.get("options") or {}).items()),
                    f"- Answer: {q.get('correctAnswer')}", f"- Image brief: {q.get('imageBrief', '(none written)')}", ""]
    return "\n".join(out)


def pr_body(branch: str, slug: str, items: list[tuple[dict, dict]], cost: float, tree: str) -> str:
    rows = []
    for paper, rep in items:
        d = rep.get("deliveredSplit") or {}
        rows.append(f"| `{paper['paperKey']}` | {paper['totalMarks']} | {paper['timeLimitSeconds'] // 60} min | "
                    f"{d.get('Easy', 0)}/{d.get('Medium', 0)}/{d.get('Hard', 0)} | {rep.get('needsHuman', 0)} |")
    return "\n".join([
        f"## {slug}: new {'university drive' if tree == 'university' else 'practice'} papers", "",
        "Generated by Paper Forge. Every question is newly written (new values, names and scenarios) and was checked "
        "against the repo and the web for originality, then rated for difficulty.", "",
        "| Paper | Marks | Time | Easy/Medium/Hard | Needs human |", "|---|---|---|---|---|", *rows, "",
        f"AI cost for this set: about ${cost:.2f} (Claude tokens + web searches).", "",
        "## Sign-off (do not merge until both are ticked)",
        *(["Coding problems are added with `status: REVIEW`. A reviewer flips them to ACTIVE after the review.", ""]
          if any(sec["type"] == "CODING" for p, _ in items for sec in p["sections"]) else []),
        *(["Audio: " + ", ".join(f"`{j['file']}`" for _, rep in items for j in (rep.get("audio") or [])) +
           " were produced by the dev team from the exact text in Paper Forge's out/audio hand-off, uploaded to Wasabi, and their URLs written into the paper (checked before publishing).", ""]
          if any(rep.get("audio") for _, rep in items) else []),
        "- [ ] Developer ran the backend and frontend on this branch and confirmed the papers load and work",
        "- [ ] Tester tested the papers and confirmed them", "",
        f"Branch: `{branch}`. Per-question reports are in Paper Forge's `out/` folder and attached below.", ""])


def preflight(cfg: Config, keys: list[str], allow_flagged: bool) -> list[tuple[dict, dict]]:
    items = []
    for k in keys:
        paper, rep = review.load(cfg, k)
        if rep.get("needsHuman") and not allow_flagged:
            raise PublishError(f"{k}: {rep['needsHuman']} question(s) need a human. Fix them in the review screen "
                               "or pass --allow-flagged.")
        v = rep.get("repoValidator") or {}
        if v.get("ran") and not v.get("ok"):
            raise PublishError(f"{k}: the repo validator failed on this draft:\n{v.get('output', '')}")
        items.append((paper, rep))
    slugs = {p["companySlug"] for p, _ in items}
    if len(slugs) != 1:
        raise PublishError(f"Publish one company at a time, got {sorted(slugs)}")
    trees = {r.get("tree", "university") for _, r in items}
    if len(trees) != 1:
        raise PublishError("Drafts were made for different trees (university and placement)")
    return items


def publish(cfg: Config, keys: list[str], *, fetch: bool = True, worktree: Path | None = None,
            commit: bool = False, allow_flagged: bool = False, allow_missing_audio: bool = False, log=print) -> dict:
    repo = cfg.repo
    if not (repo / ".git").exists():
        raise PublishError(f"{repo} is not a git repository")
    items = preflight(cfg, keys, allow_flagged)
    jobs = [j for _, rep in items for j in (rep.get("audio") or [])]
    if jobs and not allow_missing_audio:
        from . import speech
        nulls = [j["file"] for j in jobs if not j["url"]]
        if nulls:
            raise PublishError(f"{len(nulls)} audio file(s) still have no URL (null in the paper): {', '.join(nulls[:6])}"
                               f"{' ...' if len(nulls) > 6 else ''}\nThe dev team produces them from out/audio/<key>/HANDOFF.md, "
                               "uploads them to Wasabi and sends the URLs. Then run `paper-forge audio <key> --map urls.json`. "
                               "Or pass --allow-missing-audio.")
        status = speech.check_urls([j["url"] for j in jobs])
        missing = [j["file"] for j in jobs if status[j["url"]] != "ok"]
        if missing:
            raise PublishError(f"{len(missing)} audio file(s) are not uploaded yet: {', '.join(missing[:6])}"
                               f"{' ...' if len(missing) > 6 else ''}\nThe dev team produces them from out/audio/<key>/HANDOFF.md. Once uploaded, "
                               "run `paper-forge audio <key>` to confirm. Or pass --allow-missing-audio.")
    slug, tree = items[0][0]["companySlug"], items[0][1].get("tree", "university")
    keys = [p["paperKey"] for p, _ in items]
    branch = branch_name(slug, keys, tree)

    if git(repo, "rev-parse", "--verify", "--quiet", f"refs/heads/{branch}", check=False):
        raise PublishError(f"Branch {branch} already exists. Delete or rename it first; Paper Forge never overwrites a branch.")
    if worktree is None and git(repo, "status", "--porcelain", "--untracked-files=no"):
        raise PublishError(
            "Your checkout has uncommitted changes to tracked files, so switching branches here would mix them in.\n"
            "Commit or stash them, or run again with --worktree <folder> to build the branch in a separate folder.")
    if fetch:
        log("Fetching origin/main ...")
        git(repo, "fetch", "origin", "main")
    if not git(repo, "rev-parse", "--verify", "--quiet", "origin/main", check=False):
        raise PublishError("origin/main not found. Run without --no-fetch, or fetch it yourself.")

    previous = git(repo, "branch", "--show-current")
    target = repo
    if worktree is not None:
        worktree = Path(worktree).resolve()
        git(repo, "worktree", "add", "-b", branch, str(worktree), "origin/main")
        target = worktree
    else:
        git(repo, "switch", "-c", branch, "origin/main")
    log(f"Created branch {branch} from origin/main" + (f" in {target}" if worktree else ""))

    created: list[Path] = []
    modified: list[Path] = []
    try:
        result = _write_and_check(cfg, target, items, slug, tree, branch, log, created, modified)
    except Exception:
        _rollback(repo, target, worktree, branch, previous, created, modified)
        raise

    paths = result["paths"]
    git(target, "add", "--", *paths)
    if commit:
        msg = (f"feat({slug}): add {len(keys)} new {'university ' if tree == 'university' else ''}paper(s) "
               f"{', '.join(keys)}\n\nGenerated by Paper Forge. Not yet confirmed by a developer and tester.")
        git(target, "commit", "-m", msg)
        log("Committed locally (not pushed).")
    result.update({"branch": branch, "previousBranch": previous, "worktree": str(worktree) if worktree else None,
                   "committed": commit, "target": str(target)})
    from . import pr as prmod
    prmod.save_record(cfg, {"branch": branch, "slug": slug, "tree": tree, "keys": keys, "paths": result["paths"],
                            "target": str(target), "repo": str(repo), "previousBranch": previous,
                            "prDraft": result["prDraft"], "publishedAt": time.strftime("%Y-%m-%d %H:%M:%S"),
                            "signoffs": {}, "prUrl": None})
    return result


def _rollback(repo: Path, target: Path, worktree: Path | None, branch: str, previous: str,
              created: list[Path], modified: list[Path]) -> None:
    """Undo our own new branch after a failure: remove the files we created, restore the ones we edited
    (the branch was cut from origin/main with a clean tree, so only our edits are touched), switch back, drop it."""
    for f in created:
        shutil.rmtree(f, ignore_errors=True) if f.is_dir() else f.unlink(missing_ok=True)
    for f in modified:  # one at a time: a file that is not tracked (no manifest yet) must not block the others
        if git(target, "ls-files", "--", str(f), check=False):
            git(target, "checkout", "-q", "--", str(f), check=False)
        else:
            f.unlink(missing_ok=True)
    if worktree is not None:
        git(repo, "worktree", "remove", "--force", str(worktree), check=False)
    elif previous:
        git(repo, "switch", "-q", previous, check=False)
    git(repo, "branch", "-D", branch, check=False)


def _write_and_check(cfg, target: Path, items, slug, tree, branch, log, created, modified) -> dict:
    cdir = company_dir(target, slug, tree)
    if cdir is None:
        raise PublishError(f"Company {slug!r} is not in the {tree} tree on origin/main. Paper Forge does not invent "
                           "companies or rounds. Add the company first, then publish.")
    cj = cdir / "company.json"
    modified.append(cj)
    text = cj.read_text(encoding="utf-8")
    paths: list[str] = []
    for paper, rep in items:
        dest = cdir / f"{paper['paperKey']}.json"
        if dest.exists():
            raise PublishError(f"{dest.name} already exists on origin/main. Re-generate so it gets a new number.")
        dest.write_text(json.dumps(paper, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        text = add_to_pool(text, paper["roundKey"], paper["paperKey"])
        paths.append(str(dest.relative_to(target)).replace("\\", "/"))
        log(f"  wrote {paths[-1]}")
    cj.write_text(text, encoding="utf-8")
    paths.append(str(cj.relative_to(target)).replace("\\", "/"))

    keys = [k for paper, _ in items for sec in paper["sections"] if sec["type"] == "CODING" for k in sec["questions"]]
    if keys:
        for k in keys:
            src, dst = cfg.out_dir / "problems" / k, target / "problems" / k
            if not src.is_dir():
                raise PublishError(f"Coding problem draft {k} not found in out/problems")
            if dst.exists():
                raise PublishError(f"problems/{k} already exists on origin/main")
            created.append(dst)
            shutil.copytree(src, dst)
            paths.append(f"problems/{k}")
            log(f"  wrote problems/{k}")
        modified.append(target / "manifest.json")
        for k in keys:
            r = subprocess.run([sys.executable, "scripts/verify-solutions.py", "--problem", k], cwd=target,
                               capture_output=True, text=True, encoding="utf-8", errors="replace")
            if r.returncode != 0:
                raise PublishError(f"verify-solutions failed for {k}:\n{(r.stdout + r.stderr).strip()[-1200:]}")
        r = subprocess.run([sys.executable, "scripts/build-manifest.py"], cwd=target, capture_output=True, text=True,
                           encoding="utf-8", errors="replace")
        if r.returncode != 0:
            raise PublishError("build-manifest.py failed:\n" + (r.stdout + r.stderr).strip()[-1200:])
        paths.append("manifest.json")
        log("  coding problems verified and manifest regenerated")

    for paper, _ in items:
        pend = cfg.out_dir / f"{paper['paperKey']}.pending.json"
        if pend.is_file():
            note = target / "tasks" / f"paper-forge-{paper['paperKey']}-image-support.md"
            note.parent.mkdir(exist_ok=True)
            created.append(note)
            note.write_text(developer_task_md(paper["paperKey"], json.loads(pend.read_text(encoding="utf-8"))), encoding="utf-8")
            paths.append(str(note.relative_to(target)).replace("\\", "/"))
            log(f"  wrote {paths[-1]}")

    val = {"ran": False, "ok": False, "output": "validator not found"}
    validator = target / "companies" / "tools" / "validate_placement_papers.py"
    if validator.is_file():
        r = subprocess.run([sys.executable, str(validator), "--repo-root", str(target)], capture_output=True,
                           text=True, encoding="utf-8", errors="replace")
        val = {"ran": True, "ok": r.returncode == 0, "output": (r.stdout + r.stderr).strip()[-1500:]}
    if val["ran"] and not val["ok"]:
        raise PublishError("The repo validator failed on the branch:\n" + val["output"])
    log("  repo validator: " + ("PASS" if val["ran"] else "not run (validator missing)"))

    cost = sum(rep.get("costUsd", 0) + rep.get("editsCostUsd", 0) for _, rep in items)
    body = pr_body(branch, slug, items, cost, tree)
    pr_file = cfg.out_dir / f"{branch.replace('/', '_')}.pr.md"
    pr_file.write_text(body, encoding="utf-8")
    return {"paths": paths, "validator": val, "prDraft": str(pr_file)}


