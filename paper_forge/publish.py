        "     (apps/cloud-lms application-local.yaml, or set env APP_PROBLEMSET_PATH)",
        "  2. RESTART the backend. It reads the company catalog once at startup, so new papers do not appear without a restart.",
        "     ./mvnw spring-boot:run -pl apps/cloud-lms -Dspring-boot.run.profiles=local",
